-- Site Nine Project Management Database Schema
-- Created: 2026-01-30
-- Redesigned: 2026-03-03 (Daemon/Possession model — EPC-H-0008)
--
-- This database manages:
-- 1. Daemons  - Named persistent entities, role-bound, Christian-tradition name pool
-- 2. Possessions - Per-session occupancy records (a daemon possesses an agent session)
-- 3. Tasks    - Development work tracking
-- 4. Epics    - Task grouping and organization
-- 5. Messaging - Daemon-to-daemon communication

-- ============================================================================
-- DAEMONS TABLE
-- ============================================================================
-- Stores daemon entities, each bound to a role.
-- Names drawn from Christian-tradition demonology; new names generated by LLM
-- when the pool is exhausted (no daemon unused in last 3 days).
CREATE TABLE IF NOT EXISTS daemons (
    name TEXT PRIMARY KEY,                -- Daemon name (Title Case, e.g., 'Mephistopheles')
    role TEXT NOT NULL                    -- Role this daemon is bound to
        CHECK(role IN ('Administrator', 'Architect', 'Engineer', 'Tester', 'Documentarian', 'Designer', 'Inspector', 'Operator', 'Historian')),
    daemonology TEXT,                     -- Whimsical but thematic first-person bio (3-5 sentences, generated lazily)
    personality TEXT,                     -- Terse trait string (e.g., 'methodical, blunt, suspicious of shortcuts')
    incarnations INTEGER NOT NULL DEFAULT 0, -- Total times this daemon has been summoned (used for roman numeral label)
    last_possession TEXT,                 -- ISO 8601 timestamp of last possession start
    created_at TEXT NOT NULL DEFAULT (datetime('now')),

    CHECK(length(name) > 0)
);

CREATE INDEX IF NOT EXISTS idx_daemons_role ON daemons(role);
CREATE INDEX IF NOT EXISTS idx_daemons_incarnations ON daemons(incarnations);
CREATE INDEX IF NOT EXISTS idx_daemons_last_possession ON daemons(last_possession);

-- ============================================================================
-- POSSESSIONS TABLE
-- ============================================================================
-- Tracks possessions (a daemon occupying an agent session).
-- One possession per OpenCode session. Status lifecycle:
--   ROLE_PENDING -> DAEMON_PENDING -> ACTIVE -> SUSPENDED -> ACTIVE -> EXORCISED
--   or ACTIVE -> EXORCISED (fast path)
CREATE TABLE IF NOT EXISTS possessions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    daemon_name TEXT,                     -- Daemon name; NULL during ROLE_PENDING/DAEMON_PENDING
    role TEXT                             -- Role for this possession; NULL during ROLE_PENDING
        CHECK(role IS NULL OR role IN ('Administrator', 'Architect', 'Engineer', 'Tester', 'Documentarian', 'Designer', 'Inspector', 'Operator', 'Historian')),
    possession_log TEXT,                  -- Path to possession log file (includes daemon name + incarnation)

    -- Timing
    start_time TEXT,                      -- ISO 8601 start time; NULL until daemon is bound
    end_time TEXT,                        -- ISO 8601 end time; NULL while active

    -- OpenCode integration
    opencode_session_id TEXT,             -- OpenCode session ID (binds possession to session)
    mode TEXT DEFAULT 'interactive'       -- 'interactive' (Admin/Director) or 'minion' (background worker)
        CHECK(mode IN ('interactive', 'minion')),
    minion_mode_active INTEGER DEFAULT 0,   -- Whether minion mode loop is actively running (0 or 1)

    -- Status
    status TEXT NOT NULL DEFAULT 'ACTIVE'
        CHECK(status IN ('ACTIVE', 'SUSPENDED', 'EXORCISED', 'ROLE_PENDING', 'DAEMON_PENDING')),

    -- Worker PID (set by minion_worker.py; used by Inquisitor for crash detection)
    worker_pid INTEGER,                   -- OS PID of minion_worker.py process; NULL for interactive, cleared on clean shutdown

    -- Heartbeat (plugin-managed; Inquisitor uses this for rogue detection)
    last_heartbeat_at TEXT,               -- ISO 8601 last heartbeat; Inquisitor exorcises if stale > 3h

    -- Suspension
    suspension_time TEXT,                 -- When possession was suspended (ISO 8601)
    suspension_reason TEXT,               -- Why possession was suspended

    -- Epic context (optional)
    epic_id TEXT,

    created_at TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at TEXT NOT NULL DEFAULT (datetime('now')),

    -- Constraints
    CHECK(daemon_name IS NULL OR length(daemon_name) > 0),
    CHECK(possession_log IS NULL OR length(possession_log) > 0),

    -- Foreign keys
    FOREIGN KEY (daemon_name) REFERENCES daemons(name) ON DELETE RESTRICT,
    FOREIGN KEY (epic_id) REFERENCES epics(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_possessions_daemon_name ON possessions(daemon_name);
CREATE INDEX IF NOT EXISTS idx_possessions_role ON possessions(role);
CREATE INDEX IF NOT EXISTS idx_possessions_status ON possessions(status);
CREATE INDEX IF NOT EXISTS idx_possessions_epic_id ON possessions(epic_id);
CREATE INDEX IF NOT EXISTS idx_possessions_mode ON possessions(mode);
CREATE INDEX IF NOT EXISTS idx_possessions_minion_mode ON possessions(minion_mode_active);
CREATE INDEX IF NOT EXISTS idx_possessions_heartbeat ON possessions(last_heartbeat_at);
CREATE INDEX IF NOT EXISTS idx_possessions_suspended ON possessions(status, suspension_time) WHERE status = 'SUSPENDED';
CREATE UNIQUE INDEX IF NOT EXISTS idx_possessions_session_id ON possessions(opencode_session_id) WHERE opencode_session_id IS NOT NULL;

