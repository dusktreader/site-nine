-- Trigger to update epic status when task status changes
CREATE TRIGGER IF NOT EXISTS update_epic_status_on_task_change
AFTER UPDATE OF status ON tasks
WHEN NEW.epic_id IS NOT NULL
BEGIN
    UPDATE epics SET
        status = (
            CASE
                WHEN NOT EXISTS (
                    SELECT 1 FROM tasks
                    WHERE epic_id = NEW.epic_id AND status != 'COMPLETE'
                ) THEN 'COMPLETE'
                WHEN EXISTS (
                    SELECT 1 FROM tasks
                    WHERE epic_id = NEW.epic_id
                    AND status IN ('UNDERWAY', 'BLOCKED', 'REVIEW', 'PAUSED')
                ) THEN 'UNDERWAY'
                ELSE 'TODO'
            END
        ),
        completed_at = (
            CASE
                WHEN NOT EXISTS (
                    SELECT 1 FROM tasks
                    WHERE epic_id = NEW.epic_id AND status != 'COMPLETE'
                ) THEN datetime('now')
                ELSE NULL
            END
        ),
        updated_at = datetime('now')
    WHERE id = NEW.epic_id AND status != 'ABORTED';
END;

-- Trigger to update epic status when task is inserted
CREATE TRIGGER IF NOT EXISTS update_epic_status_on_task_insert
AFTER INSERT ON tasks
WHEN NEW.epic_id IS NOT NULL
BEGIN
    UPDATE epics SET
        status = (
            CASE
                WHEN NOT EXISTS (
                    SELECT 1 FROM tasks
                    WHERE epic_id = NEW.epic_id AND status != 'COMPLETE'
                ) THEN 'COMPLETE'
                WHEN EXISTS (
                    SELECT 1 FROM tasks
                    WHERE epic_id = NEW.epic_id
                    AND status IN ('UNDERWAY', 'BLOCKED', 'REVIEW', 'PAUSED')
                ) THEN 'UNDERWAY'
                ELSE 'TODO'
            END
        ),
