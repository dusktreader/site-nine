-- ============================================================================
-- TASK STATUS VIEW
-- ============================================================================
CREATE VIEW IF NOT EXISTS task_status_view AS
    SELECT
        t.id,
        t.status as work_status,
        CASE
            -- Terminal states pass through
            WHEN t.status IN ('COMPLETE', 'ABORTED') THEN t.status

            -- Check for external blocker
            WHEN EXISTS (
                SELECT 1 FROM blocks b
                WHERE b.task_id = t.id AND b.resolved_at IS NULL
                AND b.block_type != 'review' AND b.block_type != 'dependency'
            ) THEN 'BLOCKED_EXTERNAL'

            -- Check for review blocker
            WHEN EXISTS (
                SELECT 1 FROM blocks b
                WHERE b.task_id = t.id AND b.resolved_at IS NULL
                AND b.block_type = 'review'
            ) THEN 'BLOCKED_REVIEW'

            -- Check for dependency blocker
            WHEN EXISTS (
                SELECT 1 FROM task_dependencies td
                INNER JOIN tasks dep ON td.depends_on_task_id = dep.id
                WHERE td.task_id = t.id AND dep.status != 'COMPLETE'
            ) THEN 'BLOCKED_DEPENDENCY'

            -- No blockers, pass through work status
            ELSE t.status
        END as effective_status
    FROM tasks t;

